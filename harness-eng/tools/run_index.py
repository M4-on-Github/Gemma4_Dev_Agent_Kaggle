"""Counts-only index of every cluster run, for git. Standard library, Python 3.6+.

  python3 -I tools/run_index.py            # writes runs-index.md

runs/ itself never enters git: task_results.jsonl carries patches and traces carry repo text (plan.md:52).
This file keeps only run ids, settings and counts, so the record of what ran survives without the data.
GPU seconds come from logs/gpu_seconds.csv (one line per job, failed jobs included).
"""
import collections
import csv
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
RUNS = os.path.join(ROOT, "runs")


def short_model(m):
    m = m or ""
    return "31B" if "31b" in m else "E4B" if "e4b" in m.lower() else (m or "-")


def main():
    gpu = collections.defaultdict(lambda: [0, 0, set()])
    led = os.path.join(ROOT, "logs", "gpu_seconds.csv")
    if os.path.exists(led):
        with open(led) as fh:
            for row in csv.reader(fh):
                if len(row) >= 4 and row[3].isdigit():
                    g = gpu[row[0]]
                    g[0] += int(row[3])
                    g[1] += 1
                    g[2].add(row[2])
    lines = []
    for run in sorted(os.listdir(RUNS)):
        rd = os.path.join(RUNS, run)
        tr = os.path.join(rd, "task_results.jsonl")
        if run.startswith("_") or not os.path.exists(tr):
            continue
        s = {}
        if os.path.exists(os.path.join(rd, "summary.json")):
            with open(os.path.join(rd, "summary.json")) as fh:
                s = json.load(fh)
        rows = []
        with open(tr) as fh:
            for line in fh:
                if line.strip():
                    rows.append(json.loads(line))
        err = [(r.get("error") or "") for r in rows]
        g = gpu.get(run, [0, 0, set()])
        lines.append("| %s | %s | %s | %s | %d | %d | %d | %d | %d | %s | %s | %s | %s | %s |" % (
            run, "-" if run.startswith("C-") else short_model(s.get("model") or run), os.path.basename(s.get("cohort") or "-"),
            s.get("n_tasks", "-"), len(rows), sum(bool(r.get("resolved")) for r in rows),
            sum(not (r.get("patch_chars") or 0) for r in rows), sum("session timeout" in e for e in err),
            sum("turns budget" in e for e in err), s.get("concurrency", "-"), s.get("time_scale", "-"),
            "%.2f" % (s["tasks_wall_s"] / 3600) if s.get("tasks_wall_s") else "-",
            "%.2f" % (g[0] / 3600) if g[1] else "-", (s.get("started_utc") or "-")))
    out = os.path.join(ROOT, "runs-index.md")
    with open(out, "w") as fh:
        fh.write("# Run index (generated by `tools/run_index.py`; do not edit)\n\n")
        fh.write("Counts only. The run folders stay under `runs/` (gitignored, plan.md:52). Readings are in "
                 "`rounds/`.\nTime cap = rows ending in the session timeout; turns = rows ending in the turn "
                 "budget. GPU h = all jobs logged under the run id in `logs/gpu_seconds.csv`.\n\n")
        fh.write("| Run | Model | Cohort | Tasks | Rows | Resolved | Empty patch | Time cap | Turns cap | "
                 "Concurrency | Time scale | Task wall h | GPU h | Started (UTC) |\n")
        fh.write("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n")
        fh.write("\n".join(lines) + "\n")
    print("wrote %d runs to %s" % (len(lines), out))


if __name__ == "__main__":
    main()
