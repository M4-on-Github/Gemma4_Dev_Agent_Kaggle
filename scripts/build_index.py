"""Rebuild the generated index files from YAML frontmatter.

Run from anywhere: python scripts/build_index.py
Also runs automatically after every Write/Edit (see .claude/settings.json). Exits 0 even when nothing changed.

Generated files (never edit by hand):
  research/INDEX.md    papers (research/lit), Kaggle digests and threads (research/kaggle), dated notes (research/*.md)
  knowledge/INDEX.md   claims (from knowledge/claims.md headings), directions, submission proposals, critic verdicts

experiments/README.md section 3 stays the hand-written experiment index: EXP files carry no frontmatter.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def frontmatter(path: Path) -> dict:
    """Parse a flat YAML frontmatter block: `key: value` and `key: [a, b]`."""
    try:
        text = path.read_text(encoding="utf-8")
    except OSError:
        return {}
    if not text.startswith("---"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    meta = {}
    for line in text[3:end].splitlines():
        if ":" not in line or line.startswith((" ", "#")):
            continue
        key, _, value = line.partition(":")
        value = value.strip().strip('"').strip("'")
        if value.startswith("[") and value.endswith("]"):
            value = ", ".join(v.strip().strip('"\'') for v in value[1:-1].split(",") if v.strip())
        meta[key.strip()] = value
    return meta


def table(headers: list[str], rows: list[list[str]]) -> str:
    cell = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out) if rows else "_none yet_"


def write(path: Path, title: str, sections: list[tuple[str, str]]) -> None:
    body = [f"# {title}", "", "_Generated by scripts/build_index.py. Do not edit by hand._", ""]
    for heading, content in sections:
        body += [f"## {heading}", "", content, ""]
    new = "\n".join(body)
    if not path.exists() or path.read_text(encoding="utf-8") != new:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(new, encoding="utf-8", newline="\n")


def rel(p: Path, base: Path) -> str:
    return p.relative_to(base).as_posix()


def research() -> None:
    base = ROOT / "research"
    if not base.is_dir():
        return
    papers = []
    for p in sorted((base / "lit").glob("lit-*.md")):
        m = frontmatter(p)
        papers.append([f"[{m.get('id', p.stem)}]({rel(p, base)})", m.get("title", ""), m.get("year", ""),
                       m.get("topics", ""), m.get("relevance", ""), m.get("read", "")])
    digests = []
    for p in sorted((base / "kaggle" / "digests").glob("*.md"), reverse=True):
        m = frontmatter(p)
        digests.append([f"[{p.stem}]({rel(p, base)})", m.get("since", ""), m.get("items", ""), m.get("headline", "")])
    threads = []
    for p in sorted((base / "kaggle" / "threads").glob("kg-*.md")):
        m = frontmatter(p)
        threads.append([f"[{m.get('id', p.stem)}]({rel(p, base)})", m.get("title", ""), m.get("author_role", ""),
                        m.get("credibility", ""), m.get("topics", ""), m.get("last_checked", "")])
    notes = []
    for p in sorted(base.glob("*.md")):
        if p.name == "INDEX.md":
            continue
        first = next((ln.lstrip("# ").strip() for ln in p.read_text(encoding="utf-8", errors="replace").splitlines()
                      if ln.strip()), "")
        notes.append([f"[{p.stem}]({rel(p, base)})", first])
    write(base / "INDEX.md", "Research index", [
        ("Papers", table(["ID", "Title", "Year", "Topics", "Relevance", "Read"], papers)),
        ("Kaggle digests", table(["Date", "Since", "Items", "Headline"], digests)),
        ("Kaggle threads", table(["ID", "Title", "Author role", "Credibility", "Topics", "Last checked"], threads)),
        ("Dated notes", table(["File", "Title"], notes)),
    ])


CLAIM_HEAD = re.compile(r"^## (C-\d{3}): (.+)$")


def knowledge() -> None:
    base = ROOT / "knowledge"
    if not base.is_dir():
        return
    claims = []
    claims_file = base / "claims.md"
    if claims_file.is_file():
        current = None
        for line in claims_file.read_text(encoding="utf-8", errors="replace").splitlines():
            h = CLAIM_HEAD.match(line)
            if h:
                current = [h.group(1), h.group(2).strip(), "", "", ""]
                claims.append(current)
            elif current is not None:
                for i, key in ((2, "status"), (3, "confidence"), (4, "tests")):
                    m = re.match(rf"^- {key}:\s*(.*)$", line)
                    if m:
                        current[i] = m.group(1).strip()
    directions = []
    for p in sorted((base / "directions").glob("D-*.md")):
        m = frontmatter(p)
        directions.append([f"[{m.get('id', p.stem)}]({rel(p, base)})", m.get("title", ""), m.get("decision", ""),
                           m.get("status", ""), m.get("claims", ""), m.get("date", "")])
    subs = []
    for p in sorted((base / "submissions").glob("S-*.md")):
        if p.stem.endswith("-result"):
            continue
        m = frontmatter(p)
        res = frontmatter(p.with_name(p.stem + "-result.md"))
        subs.append([f"[{m.get('id', p.stem)}]({rel(p, base)})", m.get("date", ""), m.get("status", ""),
                     m.get("experiments", ""), m.get("sha256", "")[:12], res.get("public_score", "")])
    critics = []
    for p in sorted((ROOT / "experiments").glob("EXP-*/critic.md")):
        m = frontmatter(p)
        critics.append([f"[{m.get('exp', p.parent.name)}](../experiments/{p.parent.name}/critic.md)", m.get("tier", ""),
                        m.get("verdict", ""), m.get("date", "")])
    write(base / "INDEX.md", "Knowledge index", [
        ("Claims", table(["ID", "Statement", "Status", "Confidence", "Tests"], claims)),
        ("Directions", table(["ID", "Title", "Decision", "Status", "Claims", "Date"], directions)),
        ("Submission proposals", table(["ID", "Date", "Status", "Experiments", "sha256", "Public score"], subs)),
        ("Critic verdicts", table(["Experiment", "Tier", "Verdict", "Date"], critics)),
    ])


def main() -> int:
    research()
    knowledge()
    return 0


if __name__ == "__main__":
    sys.exit(main())
