#!/usr/bin/env python3
"""Deterministic, repo-stratified cohorts from the public tasks.jsonl (plan.md §5.2).

Writes task ids only (no competition data) to experiments/cohorts/:
  dev-48.txt       fastapi 22 / rich 16 / requests 9 / httpx 1  (oversamples the small repos)
  held-out-24.txt  fastapi 11 / rich 8 / requests 4 / httpx 1  — disjoint from dev-48; look at it only at gates
  smoke-8.txt      2 per repo, a subset of dev-48 (1 for httpx + 1 extra fastapi when httpx has a single task)

Tasks listed in --exclude (one id per line; EXP-000 gold-control failures) are dropped first.
If a repo has fewer tasks than requested, the remainder is filled from the largest repo and a warning is printed.

Usage:
    python tools/make_cohorts.py --tasks data/raw/tasks.jsonl --exclude runs/EXP-000/gold_failures.txt \
        --seed 20261013 --out experiments/cohorts
"""
from __future__ import annotations

import argparse
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

DEFAULT_DEV = {"fastapi/fastapi": 22, "Textualize/rich": 16, "psf/requests": 9, "encode/httpx": 1}
DEFAULT_HELD = {"fastapi/fastapi": 11, "Textualize/rich": 8, "psf/requests": 4, "encode/httpx": 1}


def parse_spec(spec: str | None, default: dict[str, int]) -> dict[str, int]:
    if not spec:
        return dict(default)
    out: dict[str, int] = {}
    for item in spec.split(","):
        repo, _, n = item.strip().partition("=")
        out[repo.strip()] = int(n)
    return out


def load_task_ids(path: Path) -> dict[str, list[str]]:
    by_repo: dict[str, list[str]] = defaultdict(list)
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line:
                continue
            row = json.loads(line)
            by_repo[str(row["repo"])].append(str(row["instance_id"]))
    return {k: sorted(set(v)) for k, v in by_repo.items()}


def draw(pool: dict[str, list[str]], spec: dict[str, int], rng: random.Random, warnings: list[str]) -> dict[str, list[str]]:
    """Take spec[repo] ids per repo from pool (mutating pool); shortfalls are filled from the largest repo."""
    chosen: dict[str, list[str]] = {}
    shortfall = 0
    for repo, n in spec.items():
        avail = pool.get(repo, [])
        take = min(n, len(avail))
        if take < n:
            warnings.append(f"{repo}: wanted {n}, only {len(avail)} available")
            shortfall += n - take
        picked = rng.sample(avail, take) if take else []
        chosen[repo] = sorted(picked)
        pool[repo] = sorted(set(avail) - set(picked))
    while shortfall > 0:
        biggest = max(pool, key=lambda r: len(pool[r]), default=None)
        if biggest is None or not pool[biggest]:
            warnings.append(f"could not fill {shortfall} missing slots")
            break
        pick = rng.choice(pool[biggest])
        pool[biggest].remove(pick)
        chosen.setdefault(biggest, []).append(pick)
        chosen[biggest].sort()
        shortfall -= 1
    return chosen


def build_cohorts(by_repo: dict[str, list[str]], *, exclude: set[str], seed: int,
                  dev_spec: dict[str, int], held_spec: dict[str, int], smoke_per_repo: int = 2
                  ) -> tuple[dict[str, dict[str, list[str]]], list[str]]:
    warnings: list[str] = []
    rng = random.Random(seed)
    pool = {repo: [t for t in ids if t not in exclude] for repo, ids in sorted(by_repo.items())}
    dev = draw(pool, dev_spec, rng, warnings)
    held = draw(pool, held_spec, rng, warnings)
    smoke: dict[str, list[str]] = {}
    short = 0
    for repo in sorted(dev):
        take = min(smoke_per_repo, len(dev[repo]))
        short += smoke_per_repo - take
        smoke[repo] = sorted(rng.sample(dev[repo], take)) if take else []
    # fill smoke shortfall (e.g. httpx has 1 task) from the largest dev repo so smoke stays at 2 x repos
    while short > 0:
        biggest = max(dev, key=lambda r: len(set(dev[r]) - set(smoke.get(r, []))))
        rest = sorted(set(dev[biggest]) - set(smoke.get(biggest, [])))
        if not rest:
            break
        smoke.setdefault(biggest, []).append(rng.choice(rest))
        smoke[biggest].sort()
        short -= 1
    return {"dev-48": dev, "held-out-24": held, "smoke-8": smoke}, warnings


def write_cohort(path: Path, name: str, chosen: dict[str, list[str]], *, seed: int, excluded: int) -> None:
    ids = sorted(t for ids in chosen.values() for t in ids)
    counts = ", ".join(f"{repo}={len(ids_)}" for repo, ids_ in sorted(chosen.items()))
    lines = [f"# cohort {name}: {len(ids)} task ids; seed={seed}; excluded={excluded}; {counts}",
             "# generated by tools/make_cohorts.py — ids only, no competition data"]
    lines += ids
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def read_cohort(path: Path) -> list[str]:
    return [ln.strip() for ln in path.read_text(encoding="utf-8").splitlines()
            if ln.strip() and not ln.startswith("#")]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--tasks", type=Path, required=True, help="tasks.jsonl (needs instance_id and repo)")
    ap.add_argument("--exclude", type=Path, help="file with task ids to drop (gold-control failures)")
    ap.add_argument("--seed", type=int, default=20261013)
    ap.add_argument("--dev-spec", help='e.g. "fastapi/fastapi=22,Textualize/rich=16,psf/requests=9,encode/httpx=1"')
    ap.add_argument("--held-spec")
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "experiments" / "cohorts")
    args = ap.parse_args(argv)
    exclude = set(read_cohort(args.exclude)) if args.exclude else set()
    by_repo = load_task_ids(args.tasks)
    cohorts, warnings = build_cohorts(by_repo, exclude=exclude, seed=args.seed,
                                      dev_spec=parse_spec(args.dev_spec, DEFAULT_DEV),
                                      held_spec=parse_spec(args.held_spec, DEFAULT_HELD))
    args.out.mkdir(parents=True, exist_ok=True)
    for name, chosen in cohorts.items():
        write_cohort(args.out / f"{name}.txt", name, chosen, seed=args.seed, excluded=len(exclude))
        n = sum(len(v) for v in chosen.values())
        print(f"{name}: {n} tasks -> {args.out / (name + '.txt')}")
    for w in warnings:
        print(f"WARNING: {w}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
